salary = 5000  # Ежемесячная зарплата
spend = 6000  # Траты за первый месяц
months = 10  # Количество месяцев для проживания без долгов
increase = 0.03  # Ежемесячный рост цен

money_capital = 0  # Начальная подушка безопасности (будем накапливать)

#Проходим по всем месяцам, накапливая необходимую сумму
for _ in range(months):
    #Сначала тратим зарплату, недостающее берём из подушки
    if spend > salary:
        money_capital += spend - salary  #Добавляем недостающую сумму
    #Расходы на следующий месяц с учётом инфляции
    spend *= (1 + increase)

#Округляем до целого числа
money_capital = int(money_capital)

print(f"Подушка безопасности, чтобы протянуть {months} месяцев без долгов:", money_capital)