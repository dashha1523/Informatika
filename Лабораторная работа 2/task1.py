money_capital = 20000  # Начальный капитал
salary = 5000  # Ежемесячный доход
spend = 6000  # Расходы первого месяца
increase = 0.05  # Ежемесячный рост цен

month = 0  # Счётчик месяцев

while True:  #Цикл до первого месяца с долгами
    budget = salary + money_capital  # Бюджет текущего месяца
    if spend > budget:  #Расходы превышают бюджет — уходим в долги
        break
    money_capital = budget - spend  #Остаток подушки безопасности
    spend *= (1 + increase)  #Расходы на следующий месяц с учётом инфляции
    month += 1

print("Количество месяцев, которое можно протянуть без долгов:", month)